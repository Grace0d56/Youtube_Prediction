import streamlit as st
import numpy as np
import pandas as pd
import unicodedata
import joblib
from tensorflow.keras.models import load_model
from tensorflow.keras.preprocessing.image import load_img, img_to_array


import streamlit as st
from googleapiclient.discovery import build

# ──────────────────────────────────────────────────────────────────────────────
# A) Load YouTube API key from secrets
YOUTUBE_API_KEY = st.secrets["youtube"]["api_key"]

# B) Cached fetch function
@st.cache_resource
def fetch_category_map(region_code="US"):
    """
    Returns a dict: {categoryId (int): categoryName (str)}
    """
    youtube = build("youtube", "v3", developerKey=YOUTUBE_API_KEY)
    resp = (
        youtube.videoCategories()
               .list(part="snippet", regionCode=region_code)
               .execute()
    )
    mapping = {
        int(item["id"]): item["snippet"]["title"]
        for item in resp["items"]
        if item["snippet"]["assignable"]  # only categories you can actually assign
    }
    return mapping

CATEGORY_MAP   = fetch_category_map("US")       # or your preferred country code
NAME_TO_ID     = {v:k for k,v in CATEGORY_MAP.items()}
CATEGORY_NAMES = list(CATEGORY_MAP.values())


# ──────────────────────────────────────────────────────────────────────────────
# 1) Load artifacts (cached so it only runs once)
@st.cache_resource
def load_artifacts():
    model    = load_model("model2.keras")
    scaler   = joblib.load("scaler2.pkl")
    tab_cols = joblib.load("tab_cols2.pkl")
    return model, scaler, tab_cols

model, scaler, tab_cols = load_artifacts()

# ──────────────────────────────────────────────────────────────────────────────
# ──────────────────────────────────────────────────────────────────────────────
# 2) Build UI
# ──────────────────────────────────────────────────────────────────────────────
import datetime

st.title("YouTube Views Predictor")

st.sidebar.header("Tabular Inputs")

# 1) Likes (optional for pre-publish)
use_likes = st.sidebar.checkbox(
    "Do you already know the like count?", 
    value=False,
    help="Check if your video is already live and you have a like count so far."
)
if use_likes:
    likes = st.sidebar.number_input(
        "Likes so far", 
        min_value=0, 
        value=0, 
        help="Number of likes your video has received to date."
    )
else:
    likes = 0
    st.sidebar.markdown(
        "_You can leave **Likes** blank if predicting before publish; it will default to 0._"
    )

# 2) Subscribers
subscribers = st.sidebar.number_input(
    "Subscribers", 
    min_value=0, 
    value=10000,
    help="Your channel’s current subscriber count."
)

# 3) Publish date & hour
publish_date = st.sidebar.date_input(
    "Publish Date",
    value=datetime.date.today(),
    help="Select the date your video will (or did) publish."
)
publish_hour = st.sidebar.slider(
    "Publish Hour (0–23)", 
    min_value=0, max_value=23, value=12,
    help="The hour of day your video publishes."
)

# 4) Cyclic encoding of hour
r = 2 * np.pi * publish_hour / 24
hour_sin = np.sin(r)
hour_cos = np.cos(r)

# 5) Region & Category picks
regions    = sorted(c.split("_",1)[1] for c in tab_cols if c.startswith("region_"))
region     = st.sidebar.selectbox("Region", regions)

category_name = st.sidebar.selectbox(
    "Category", 
    sorted(CATEGORY_NAMES),
    help="Official YouTube category names"
)
category_id = NAME_TO_ID[category_name]

# 6) Derive day_of_week from the calendar date
day_of_week = publish_date.strftime("%A")  # e.g. "Monday", "Tuesday", etc.

# 7) Title & symbol count
title        = st.sidebar.text_input("Video Title (optional)")
symbol_count = sum(unicodedata.category(c).startswith("So") for c in title)

# 3) Image uploader
st.header("Upload Thumbnail")
uploaded_file = st.file_uploader("Choose a JPG/PNG", type=["jpg","jpeg","png"])
if not uploaded_file:
    st.warning("Please upload a thumbnail image.")
    st.stop()

img = load_img(uploaded_file, target_size=(128,128))

img_arr = img_to_array(img) / 255.0
st.image(img, use_container_width=True)

# ──────────────────────────────────────────────────────────────────────────────
# 4) Assemble tabular feature vector
# ──────────────────────────────────────────────────────────────────────────────
row = dict.fromkeys(tab_cols, 0.0)
row.update({
    "likes":        likes,
    "subscribers":  subscribers,
    "hour_sin":     hour_sin,
    "hour_cos":     hour_cos,
    "symbol_count": symbol_count,
})

# set region dummy only if that column exists
reg_col = f"region_{region}"
if reg_col in tab_cols:
    row[reg_col] = 1.0

# set day_of_week dummy only if that column exists
dow_col = f"day_of_week_{day_of_week}"
if dow_col in tab_cols:
    row[dow_col] = 1.0

# set category_id dummy only if that column exists
cat_col = f"category_id_{category_id}"
if cat_col in tab_cols:
    row[cat_col] = 1.0

X_tab = pd.DataFrame([row], columns=tab_cols)
X_tab_scaled = scaler.transform(X_tab)


# ──────────────────────────────────────────────────────────────────────────────
# 5) Predict
# ──────────────────────────────────────────────────────────────────────────────
# Prepare image
X_img_input = np.expand_dims(img_arr, axis=0)   # shape (1,128,128,3)

# Raw model output in √-space:
y_model_out = model.predict([X_img_input, X_tab_scaled])[0,0]
st.write("Raw model output:", y_model_out)

# Back-transform:
# If trained on sqrt(views):
y_pred = float(y_model_out) ** 2

# If you had trained on log1p(views), instead use:
# y_pred = np.expm1(y_model_out)

# ──────────────────────────────────────────────────────────────────────────────
# 6) Display result
# ──────────────────────────────────────────────────────────────────────────────
st.subheader("Estimated View Count")
st.markdown(f"### **{y_pred:,.0f}** views")

